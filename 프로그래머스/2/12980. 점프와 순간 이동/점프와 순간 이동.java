/*
한 번에 k칸을 앞으로 점프하거나, (현재까지 온 거리) x 2에 해당하는 위치 순간이동 가능 슈트
K 칸을 점프하면 K 만큼의 건전지 사용량, 순간이동 건전지 사용 X 
순간 이동을 하는 것이 더 효율적임

[목표]
아이언 슈트를 착용하고 거리가 n 만큼 떨어져있는 장소로 가야함
건전지 사용량을 줄이기 위해 점프로 이동하는 것 최소화
거리 n이 주여졌을 때 사용해야 하는 건전지 사용량의 최솟값 return
*/

/*
[접근]
1. 맨 처음은 무조건 특정 거리만큼 뛰어야 함
2. 만약 m만큼 뛰었고 다음에는 순간이동을 한다면 2m으로 위치 이동함
3. 순간이동 했을 때 2m < n이어야 하고 최대한 n에 가까워야 함
4. while문으로 m 증가 시키면서 n이랑 최대한 가깝게 위치하도록 설계?

5000 2500 1250 625 624(1) 312 156 78 39 38(2) 19 18(3) 9 8(4) 4 2 1 0(5) 
*/

import java.util.*;

public class Solution {
    public int solution(int n) {
        
        int battery = 0;
        
        while (n > 0) {
            if (n % 2 != 0) {          
                n -= 1;
                battery++;   
            }
            
            n /= 2;
        }
        
        return battery;
    }
}
